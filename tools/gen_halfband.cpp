// Generates src/halfband.h: integer half-band decimation filters (Q31), one table per stage counted from the base rate upwards.
// Ratios only: passband edge 0.90*B, stage k stopband starts at (fs_out - 0.90*B), B = base Nyquist. Stopband target 120 dB.
// The generated header is the normative constant table; the decoder never designs filters at run time.
#include <cstdio>
#include <cmath>
#include <cstdint>
#include <vector>
using namespace std;
static double I0(double x) { double s = 1, t = 1; for (int k = 1; k < 100; k++) { t *= (x / 2 / k) * (x / 2 / k); s += t; } return s; }
int main() {
    const double A = 120.0, beta = 0.1102 * (A - 8.7);
    FILE* f = fopen("../src/halfband.h", "w");
    fprintf(f, "// SPDX-FileCopyrightText: 2026 mtq0605\n// SPDX-License-Identifier: Apache-2.0\n// GENERATED by tools/gen_halfband.cpp - normative integer tables (Q31). Do not edit.\n#pragma once\n#include <cstdint>\n");
    fprintf(f, "namespace lae {\n");
    int nst = 4;
    for (int s = 0; s < nst; s++) {
        // stage s decimates from fs_in = 4B * 2^s  to fs_out = 2B * 2^s (B = base Nyquist = 1.0)
        double fin = 4.0 * (1 << s), fout = fin / 2;
        double df = ((fout - 0.90) - 0.90) / fin;          // normalised transition width
        int N = (int)ceil((A - 7.95) / (14.36 * df));
        int half = (N + 1) / 2; if (half % 2 == 0) half++;   // centre tap index range +-half, half odd
        // taps h[n], n=-half..half; half-band: h0=0.5, even n!=0 -> 0, odd n: 0.5*sinc(n/2)
        vector<double> h(2 * half + 1, 0.0);
        double sumOdd = 0;
        for (int n = 1; n <= half; n += 2) {
            double ideal = sin(M_PI * n / 2.0) / (M_PI * n);
            double r = (double)n / (half + 1);
            double w = I0(beta * sqrt(1 - r * r)) / I0(beta);
            h[half + n] = h[half - n] = ideal * w;
            sumOdd += 2 * ideal * w;
        }
        double sc = 0.5 / sumOdd;   // total DC gain exactly 1 with centre 0.5
        vector<int64_t> q(half + 1, 0);
        int64_t total = 0;
        for (int n = 1; n <= half; n += 2) { q[n] = (int64_t)llround(h[half + n] * sc * 2147483648.0); total += 2 * q[n]; }
        int64_t centre = 1LL << 30;
        int64_t err = (1LL << 31) - centre - total;          // push rounding residue into the largest tap
        q[1] += err / 2;
        fprintf(f, "// stage %d: %.0f -> %.0f x B, half-length %d (%d taps)\n", s, fin, fout, half, 2 * half + 1);
        fprintf(f, "static const int kHalfLen%d = %d;\n", s, half);
        fprintf(f, "// odd taps h[1], h[3], ... h[%d] (symmetric); centre tap = 2^30\n", half);
        fprintf(f, "static const int32_t kHalf%d[%d] = {", s, (half + 1) / 2);
        for (int n = 1, c = 0; n <= half; n += 2, c++) fprintf(f, "%s%lld", c ? ", " : "", (long long)q[n]);
        fprintf(f, "};\n");
        printf("stage %d: df %.4f N %d half %d, DC residue fixed %lld\n", s, df, N, half, (long long)(err));
    }
    fprintf(f, "}\n");
    fclose(f);
    return 0;
}
